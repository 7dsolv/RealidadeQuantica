function p=part(ref,value,kind,x,y,pads,nets,box)
p=struct('ref',ref,'value',value,'kind',kind,'xy_mm',[x y], ...
    'pads_mm',pads,'net_codes',nets,'body_mm',box);
end
function r=route(net,layer,points)
r=struct('net',net,'layer',layer,'points_mm',points,'width_mm',0.35);
if net==2, r.width_mm=0.5; end
end
